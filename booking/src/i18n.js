export const t = (lang) => STRINGS[lang] || STRINGS.en;

/** Serialisable copy for the browser (functions become sample-free; the client has its own duration formatter). */
export function clientStrings(lang) {
  const s = t(lang);
  return Object.fromEntries(Object.entries(s).filter(([, v]) => typeof v === 'string'));
}
